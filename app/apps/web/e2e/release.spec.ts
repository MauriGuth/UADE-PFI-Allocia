import { test, expect } from '@playwright/test';

test('registro, cartera sin cotización, alertas, exportación, revocación y baja', async ({ page, context, request }) => {
  test.setTimeout(60000);
  const email = `release-${Date.now()}@example.test`;
  const password = 'Release-isolated-1234';
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.clock.install();
  await page.goto('/register');
  await page.getByLabel('Nombre', {exact:true}).fill('Prueba Release');
  await page.getByLabel('Email', {exact:true}).fill(email);
  await page.getByLabel('Contraseña', {exact:true}).fill(password);
  await expect(page.getByRole('button', {name:'Crear cuenta'})).toBeDisabled();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', {name:'Crear cuenta'}).click();
  await expect(page).toHaveURL(/\/resumen/);
  const cookie = (await context.cookies()).find(c => c.name === 'allocia_token')!;
  expect(cookie.httpOnly).toBe(true);
  expect(cookie.sameSite).toBe('Strict');
  await page.goto('/cartera');
  await page.getByLabel('Ticker / Símbolo').fill('AAPL');
  await page.getByLabel('Cantidad (en unidades)', {exact:true}).fill('2,5');
  await page.getByRole('button', {name:/Agregar Activo/}).click();
  await expect(page.getByRole('button', {name:'Editar AAPL'}).first()).toBeVisible();
  // Source outage affects valuation only, never ownership or editing.
  await page.route('**/api/proxy/portfolio', route => route.fulfill({status:503,contentType:'application/json',body:'{"message":"Fuente no disponible"}'}));
  await page.reload();
  await expect(page.getByText('Valuación no disponible', {exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Editar AAPL'}).first().click();
  await page.getByLabel('Nueva cantidad').fill('4');
  const saved=page.waitForResponse(response=>response.request().method()==='PATCH' && /\/api\/proxy\/portfolio\/positions\/\d+$/.test(response.url()));
  await page.getByRole('button', {name:'Guardar',exact:true}).click();
  expect((await saved).ok()).toBe(true);
  const holdings = await page.request.get('/api/proxy/portfolio/holdings');
  expect((await holdings.json())[0].quantity).toBe(4);
  // Background refresh preserves an unfinished position form.
  let polls=0;
  await page.route('**/api/proxy/portfolio', route => {polls++;return route.fulfill({status:503,contentType:'application/json',body:'{"message":"Fuente no disponible"}'});});
  if (!(await page.getByLabel('Ticker / Símbolo').isVisible())) await page.getByRole('button', {name:'Agregar activo',exact:true}).click();
  await page.getByLabel('Ticker / Símbolo').fill('MSFT');
  await page.getByLabel('Cantidad (en unidades)',{exact:true}).fill('7');
  await page.clock.fastForward(30_100);
  await expect.poll(()=>polls).toBeGreaterThan(0);
  await expect(page.getByLabel('Ticker / Símbolo')).toHaveValue('MSFT');
  await expect(page.getByLabel('Cantidad (en unidades)',{exact:true})).toHaveValue('7');
  await page.clock.resume();
  await page.goto('/market');
  await expect(page.getByRole('heading', {name:'Mercados y alertas'})).toBeVisible();
  await page.getByText('Configuración y cobertura de las alertas', {exact:true}).click();
  await page.getByRole('button', {name:'Activar alertas de mi cartera'}).click();
  await expect(page.getByRole('button', {name:'Desactivar alertas'})).toBeVisible();
  const exported = await page.request.get('/api/proxy/auth/export');
  expect((await exported.json()).positions[0].quantity).toBe(4);
  const forged = await page.request.patch('/api/proxy/market/preferences', {headers:{Origin:'https://evil.example'},data:{enabled:false}});
  expect(forged.status()).toBe(403);
  const missing = await page.request.post('/api/auth/logout');
  expect(missing.status()).toBe(403);
  await page.goto('/account');
  await page.getByRole('button', {name:'Cerrar sesión',exact:true}).click();
  await expect(page).toHaveURL(/\/login/);
  const revoked = await request.get('/api/proxy/portfolio/holdings', {headers:{Cookie:`allocia_token=${cookie.value}`}});
  expect(revoked.status()).toBe(401);
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Contraseña',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Iniciar sesión'}).click();
  await expect(page).toHaveURL(/\/resumen/);
  await page.goto('/account');
  await page.getByLabel('Confirmá tu contraseña').fill(password);
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Eliminar mi cuenta y datos'}).click();
  await expect(page).toHaveURL(/\/login/);
  expect(errors).toEqual([]);
});
